// Polaroid palette per type (style.css --tt-*): base fill, light highlight, glow = dark shade
const tone = (k) => ({
  get base() { return css(`--tt-${k}`); },
  get light() { return css(`--tt-${k}-light`); },
  get glow() { return css(`--tt-${k}-dark`); },
});
export const COLORS = {
  I: tone('i'),
  O: tone('o'),
  T: tone('t'),
  S: tone('s'),
  Z: tone('z'),
  J: tone('j'),
  L: tone('l'),
};

export const TYPES = ['I', 'J', 'L', 'O', 'S', 'T', 'Z'];

// wall kicks: y is up-positive (SRS convention); applied with y negated
const KICKS_JLSTZ = {
  '0>1': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '1>0': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '1>2': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '2>1': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '2>3': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '3>2': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '3>0': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '0>3': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
};
const KICKS_I = {
  '0>1': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
  '1>0': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
  '1>2': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
  '2>1': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
  '2>3': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
  '3>2': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
  '3>0': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
  '0>3': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
};

export function getKicks(type, from, to) {
  if (type === 'O') return [[0, 0]];
  const table = type === 'I' ? KICKS_I : KICKS_JLSTZ;
  return table[`${from}>${to}`] || [[0, 0]];
}

export function spawnPiece(type) {
  return { type, rot: 0, x: 3, y: 0 };
}

export function cellsOf(piece, rot = piece.rot) {
  return SHAPES[piece.type][rot].map(([cx, cy]) => [piece.x + cx, piece.y + cy]);
}
